def csv_rows(recs):
    hdr = ["rank", "slug", "name", "interest_0_10", "credibility_0_10", "status", "needs_recheck",
           "cost_of_entry_usd", "max_sane_budget_usd", "ev_at_100usd", "ev_at_1000usd",
           "verified_on", "stale_risk", "x_handle", "one_line_verdict"]
    rows = [hdr]
    for r in sorted(recs.values(), key=lambda x: x["rank"]):
        def ev(b):
            best, d = 0.0, 10 ** 9
            for x in r["returns"]:
                dd = abs(x["budget_usd"] - b)
                if dd < d:
                    d, best = dd, x.get("expected_usd", 0.0)
            return "" if best is None else f"{best:+.0f}"
        rows.append([r["rank"], r["slug"], r["name"], r["score"]["interest"], r["score"]["trust"], r["status"],
                     str(r["needs_recheck"]).lower(), r["cost_of_entry_usd"], r["max_sane_budget_usd"],
                     ev(100), ev(1000), r["verified_on"], r["stale_risk"], r["links"].get("x") or "",
                     r["verdict_short"].replace("\n", " ")])
    return rows


def matrix(recs):
    budgets = [0, 100, 500, 1000, 5000, 10000]
    order = sorted(recs.values(), key=lambda x: x["rank"])
    out = ["| งบ | " + " | ".join(r["name"] for r in order) + " |", "|---:" + "|---:" * len(order)]
    for b in budgets:
        cells = []
        for r in order:
            best, d = None, 10 ** 9
            for x in r["returns"]:
                dd = abs(x["budget_usd"] - b)
                if dd < d:
                    d, best = dd, x.get("expected_usd")
            cells.append("—" if best is None else f"{best:+,.0f}")
        out.append(f"| ${b:,} | " + " | ".join(cells) + " |")
    return "\n".join(out)


