def main():
    check_only = "--check" in sys.argv
    recs = load()
    problems = validate(recs)
    if problems:
        print("VALIDATION FAILED:")
        for p in problems:
            print("  -", p)
        raise SystemExit(1)
    if check_only:
        print(f"OK: {len(recs)} records validate against {len(REQUIRED)} required keys")
        return
    written = []
    for r in recs.values():
        written.append(write(f"data/projects/{r['slug']}.json", json.dumps(to_json_record(r), ensure_ascii=False, indent=2) + "\n"))
