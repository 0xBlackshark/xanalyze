def load():
    recs = {}
    for src in (_A, _B, _C):
        recs.update(src)
    for slug, rec in recs.items():
        if slug not in META:
            raise SystemExit(f"build.py: {slug} missing entry in tools/data_meta.py")
        m = dict(META[slug])
        rec["value_for_money"] = m["value_for_money"]
        rec["cost_of_entry_usd"] = m["budget_min_usd"]
        rec["max_sane_budget_usd"] = m["budget_max_sane_usd"]
        rec["capital_rule"] = m["capital_rule"]
        rec["verified_on"] = m["verified_on"]
        sr = str(rec.get("stale_risk", ""))
        if "\u2014" in sr:                       # "level — reason" in the source data -> split for the schema enum
            lvl, note = [x.strip() for x in sr.split("\u2014", 1)]
            rec["stale_risk"], rec["stale_risk_note"] = lvl, note
        rec["needs_recheck"] = rec.get("links", {}).get("x") in (None, "") or "ไม่ถูกบันทึก" in " ".join(map(str, rec.get("history", [])))
        rec["schema_version"] = SCHEMA_VERSION
        rec["generated_from"] = GENERATED_NOTE
    order = sorted(recs.values(), key=lambda r: r["rank"])
    for i, r in enumerate(order, 1):
        r["rank"] = i
    return {r["slug"]: r for r in order}


def validate(recs):
    problems = []
    for slug, r in recs.items():
        for k in REQUIRED:
            if k not in r or r[k] in (None, "", [], {}):
                if not (k == "links" and True):
                    problems.append(f"{slug}: missing/empty required key '{k}'")
        for s in ("interest", "trust"):
            v = r.get("score", {}).get(s)
            if not isinstance(v, (int, float)) or not 0 <= v <= 10:
                problems.append(f"{slug}: score.{s}={v!r} out of range 0..10")
        budgets = [x.get("budget_usd") for x in r.get("returns", [])]
        if len(budgets) < 4 or budgets != sorted(budgets):
            problems.append(f"{slug}: returns[] must be >=4 rungs sorted by budget_usd (got {budgets})")
        if not r.get("unverified"):
            problems.append(f"{slug}: unverified[] is mandatory (honesty field)")
        if not r.get("technical", {}).get("onchain"):
            problems.append(f"{slug}: technical.onchain[] empty")
    return problems


def to_json_record(r):
    """Stable key order: identity -> scores -> 10 fields -> evidence -> meta."""
    keys = ["slug", "schema_version", "name", "aliases", "rank", "status", "links", "chain", "legal_entity",
            "score", "field2_interest", "trust_evidence", "model", "how_to_play", "risks",
            "value_for_money", "house_edge", "cost_of_entry_usd", "opportunity", "returns",
            "max_sane_budget_usd", "capital_rule", "history", "technical", "verdict_short",
            "unverified", "watch", "needs_recheck", "stale_risk", "stale_risk_note", "verified_on", "sources", "generated_from"]
    return {k: r[k] for k in keys if k in r}


def bullets(items, prefix="- "):
    return "\n".join(f"{prefix}{i}" for i in items) if items else "- (ไม่มีข้อมูล)"


